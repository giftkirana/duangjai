def esc(s):
    return html.escape(s, quote=True)

def thai_date(d):
    return f"วัน{TH_DOW[d.weekday()]}ที่ {d.day} {TH_MONTHS[d.month - 1]} {d.year + 543}"

def reading(d, i):
    r = random.Random(d.toordinal() * 31 + i * 977)
    lvl, over = r.choice(OVER)
    nums = sorted(r.sample(range(10), 2))
    good_c, bad_c = r.sample(COLORS, 2)
    return dict(level=lvl, over=over, work=r.choice(WORK), money=r.choice(MONEY),
                single=r.choice(LOVE_S), couple=r.choice(LOVE_P), health=r.choice(HEALTH),
                color=good_c, avoid_color=bad_c, time=r.choice(TIMES), dir=r.choice(DIRS),
                nums=f"{nums[0]}{nums[1]} · {nums[1]}{nums[0]}", do=r.choice(DO), dont=r.choice(AVOID))

def shell(title, desc, canon, body, depth="../"):
    return (f'<!DOCTYPE html><html lang="th"><head><meta charset="utf-8">{ADS}'
            f'<meta name="viewport" content="width=device-width,initial-scale=1"><title>{esc(title)}</title>'
            f'<meta name="description" content="{esc(desc)}"><link rel="canonical" href="{canon}">'
            f'<meta property="og:title" content="{esc(title)}"><meta property="og:description" content="{esc(desc)}">'
            f'<link rel="stylesheet" href="{depth}style.css"></head><body><div class="w">{body}'
            f'<p class="note"><a href="{depth}about">เกี่ยวกับเรา</a> · <a href="{depth}privacy">นโยบายความเป็นส่วนตัว</a> · '
            f'<a href="{depth}contact">ติดต่อเรา</a><br>คำทำนายเพื่อความบันเทิง ไม่ควรใช้ตัดสินใจเรื่องสำคัญ</p></div></body></html>')

